// Writes src/lib/data/index.ts: the one import screens use for data. Each function comes from
// the live (Supabase) layer when DATA_SOURCE=supabase, otherwise from the sample-data layer.
// Run after adding a data function: node scripts/gen-data-index.mjs
import fs from "node:fs";
const dir = "src/lib/data";
const demo = fs.readFileSync(`${dir}/demo.ts`, "utf8");
const mods = [...demo.matchAll(/export \* from "\.\/([\w-]+)"/g)].map((m) => m[1]);
const fns = [], consts = [], types = [];
for (const m of mods) {
  const src = fs.readFileSync(`${dir}/${m}.ts`, "utf8");
  for (const x of src.matchAll(/^export (?:async )?function (\w+)/gm)) fns.push(x[1]);
  for (const x of src.matchAll(/^export const (\w+)/gm)) consts.push(x[1]);
  for (const x of src.matchAll(/^export (?:type|interface) (\w+)/gm)) types.push(x[1]);
}
const out = `// GENERATED by scripts/gen-data-index.mjs. Do not edit by hand.
// The one import screens use for data. Same names and signatures in both builds.
import "server-only";
import { LIVE } from "../mode";
import * as demo from "./demo";
import * as liveModule from "./live";
import { onLive } from "./live/run";

// Type check: every live function must match its sample-data twin exactly.
const live: Partial<typeof demo> = liveModule;

function notReady(name: string): never {
  throw new Error(\`\${name} isn't connected to Supabase yet\`);
}
/**
 * Live build: a function written for Supabase if there is one (live/*.ts), otherwise the
 * sample-data logic run on the signed-in person's slice of the database (live/run.ts).
 */
function pick<K extends keyof typeof demo>(name: K): (typeof demo)[K] {
  if (!LIVE) return demo[name];
  const own = live[name];
  if (own) return own as (typeof demo)[K];
  const fn = demo[name] as unknown as (...a: unknown[]) => unknown;
  return (fn.constructor.name === "AsyncFunction" ? onLive(fn) : fn) as (typeof demo)[K];
}
void notReady;

${fns.map((f) => `export const ${f} = pick("${f}");`).join("\n")}

export { ${consts.join(", ")} } from "./demo";
${types.length ? `export type { ${types.join(", ")} } from "./demo";` : ""}
export type * from "./types";
`;
fs.writeFileSync(`${dir}/index.ts`, out);
console.log(`index.ts: ${fns.length} functions, ${consts.length} constants`);
